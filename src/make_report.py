"""Generate docs/Experiment_Results.md from the saved JSON outputs (no numbers typed by hand).

Run:  python -m src.make_report
"""
import json

from . import config as C


def _load(p):
    return json.loads(p.read_text()) if p.exists() else None


def build() -> str:
    ev, ex, kr = _load(C.evaluation_path()), _load(C.experiments_path()), _load(C.keras_results_path())
    out = ["# Experiment Results", "", "_Generated by `python -m src.make_report` from `outputs/*.json`. "
           "Every value below was computed from real model outputs._", ""]
    if not ev:
        return "\n".join(out + ["No evaluation results found. Run `python -m src.train` first."])
    m, t = ev["meta"], ev["test"]
    cfg = m["config"]
    out += ["## 1. Setup", "",
            f"- Architecture: {' → '.join(map(str, m['layer_sizes']))} ({m['n_parameters']:,} trainable parameters)",
            f"- Optimizer: {cfg['optimizer']} (momentum {cfg['momentum']}), learning rate {cfg['learning_rate']}, "
            f"decay {cfg['lr_decay']} per epoch, L2 {cfg['l2']}, batch size {cfg['batch_size']}, seed {cfg['seed']}",
            f"- Split: {m['split']['train']:,} train / {m['split']['val']:,} validation / {m['split']['test']:,} test",
            f"- Epochs run: {m['epochs_run']} of {cfg['epochs']} (early-stopping patience {cfg['patience']}); "
            f"best epoch (lowest validation loss): {m['best_epoch']}",
            f"- Training time: {m['train_seconds']:.1f} s", ""]
    out += ["## 2. Accuracy and loss", "", "| Split | Images | Accuracy | Loss |", "|---|---|---|---|"]
    for k, name in (("train", "Training"), ("validation", "Validation"), ("test", "Test")):
        out.append(f"| {name} | {ev[k]['n']:,} | {ev[k]['accuracy']:.4%} | {ev[k]['loss']:.4f} |")
    out += ["", f"Test set: **{t['correct']:,} correct, {t['incorrect']:,} incorrect**.", "",
            "## 3. Per-class metrics (test set)", "", "| Digit | Precision | Recall | F1 | Support |", "|---|---|---|---|---|"]
    for d, r in t["per_class"].items():
        out.append(f"| {d} | {r['precision']:.4f} | {r['recall']:.4f} | {r['f1']:.4f} | {r['support']} |")
    for k in ("macro", "weighted"):
        r = t[k]
        out.append(f"| **{k} avg** | {r['precision']:.4f} | {r['recall']:.4f} | {r['f1']:.4f} | {t['n']} |")
    out += ["", "## 4. Most frequent confusions (test set)", "", "| Actual | Predicted | Count |", "|---|---|---|"]
    out += [f"| {c['true']} | {c['pred']} | {c['count']} |" for c in t["top_confusions"]]
    if kr:
        out += ["", "## 5. NumPy ANN vs TensorFlow/Keras MLP", "",
                "| Implementation | Optimizer | Test accuracy | Test loss | Epochs run | Training time (s) | Parameters |",
                "|---|---|---|---|---|---|---|",
                f"| NumPy (from scratch) | {cfg['optimizer']} + L2 + lr decay | {t['accuracy']:.4%} | {t['loss']:.4f} | "
                f"{m['epochs_run']} | {m['train_seconds']:.1f} | {m['n_parameters']:,} |"]
        for name, r in kr.items():
            out.append(f"| Keras | {name} | {r['test_accuracy']:.4%} | {r['test_loss']:.4f} | {r['epochs_run']} | "
                       f"{r['train_seconds']:.1f} | {r['trainable_parameters']:,} |")
        out += ["", "Timings were measured on one CPU core and depend on the machine; both include per-epoch validation."]
    if ex:
        out += ["", f"## 6. Hyper-parameter experiments ({ex['epochs']} epochs each, validation set only)", "",
                "| Group | Setting | Validation accuracy | Validation loss | Final training accuracy | Time (s) |",
                "|---|---|---|---|---|---|"]
        out += [f"| {r['group']} | {r['setting']} | {r['val_accuracy']:.4%} | {r['val_loss']:.4f} | "
                f"{r['final_train_accuracy']:.4%} | {r['seconds']:.0f} |" for r in ex["rows"]]
        out += ["", "With 6,000 validation images, differences of roughly 0.3 percentage points are within noise."]
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    p = C.ROOT / "docs" / "Experiment_Results.md"
    p.write_text(build())
    print("wrote", p)
